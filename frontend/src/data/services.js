export const createServiceBanner = (title, subtitle, accentHex = '#38bdf8', bgHex = '#0c4a6e') => {
  const safeTitle = (title || '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  const safeSubtitle = (subtitle || '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="800" height="500" viewBox="0 0 800 500">
    <defs>
      <linearGradient id="g" x1="0%" y1="0%" x2="100%" y2="100%">
        <stop offset="0%" stop-color="${bgHex}" />
        <stop offset="100%" stop-color="#0f172a" />
      </linearGradient>
    </defs>
    <rect width="800" height="500" fill="url(#g)" rx="16" />
    <circle cx="680" cy="110" r="140" fill="${accentHex}" opacity="0.18" />
    <circle cx="110" cy="420" r="170" fill="${accentHex}" opacity="0.12" />
    <rect x="56" y="64" width="180" height="34" rx="17" fill="${accentHex}" opacity="0.25" />
    <text x="146" y="86" font-family="Inter, Arial, sans-serif" font-size="13" font-weight="700" fill="#ffffff" text-anchor="middle" letter-spacing="1.5">VENTO SERVICIOS</text>
    <text x="56" y="240" font-family="Inter, Arial, sans-serif" font-size="30" font-weight="800" fill="#ffffff">${safeTitle.slice(0, 36)}</text>
    ${safeTitle.length > 36 ? `<text x="56" y="278" font-family="Inter, Arial, sans-serif" font-size="22" font-weight="700" fill="#cbd5e1">${safeTitle.slice(36, 75)}</text>` : ''}
    <text x="56" y="324" font-family="Inter, Arial, sans-serif" font-size="18" font-weight="500" fill="${accentHex}">${safeSubtitle}</text>
    <line x1="56" y1="365" x2="220" y2="365" stroke="${accentHex}" stroke-width="5" stroke-linecap="round" />
  </svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
};

